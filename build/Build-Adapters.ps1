#Requires -Version 7.4
<#
.SYNOPSIS
    Generates integrations/<agent>/ from core/agents/. See ADR-0003.
.PARAMETER OutputRoot
    Folder to render into (default: integrations/). Test-Drift.ps1 renders into a temp folder and compares.
    Dot-folders are stored as dot-<name> (dot-claude, dot-github, dot-agents, dot-cursor); the installer maps
    them to .<name> in the target repository. This keeps the distribution repository from loading its own
    adapters and lets tooling that protects dot-folders handle the files.
#>
[CmdletBinding()]
param([string] $OutputRoot)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out = if ($OutputRoot) { $OutputRoot } else { Join-Path $root 'integrations' }
$agents = Join-Path $root 'core' 'agents'
$kit = '.speckit/radzen'
$version = (Get-Content (Join-Path $root 'VERSION') -Raw).Trim()
$utf8 = [System.Text.UTF8Encoding]::new($false)
$generatedNote = "<!-- Generated by build/Build-Adapters.ps1 (Spec Kit Radzen $version). Do not edit; change core/agents/ instead. -->"

function Save([string] $relative, [string] $text) {
    $path = Join-Path $out $relative
    $dir = Split-Path $path -Parent
    if (-not (Test-Path $dir)) { $null = New-Item -ItemType Directory -Path $dir -Force }
    [System.IO.File]::WriteAllText($path, (($text -replace "`r`n", "`n").TrimEnd() + "`n"), $utf8)
}
function Read-Source([string] $name) { (Get-Content (Join-Path $agents $name) -Raw).Replace('{{KIT}}', $kit) }
function Strip-Title([string] $md) { ($md -replace '^\s*#\s+[^\n]*\n', '').Trim() }

if (Test-Path $out) { Get-ChildItem -Path $out -Force | Remove-Item -Recurse -Force }
$null = New-Item -ItemType Directory -Force -Path $out

$contract = Read-Source 'operating-contract.md'
$contractBody = Strip-Title $contract
$razorRules = Strip-Title (Read-Source 'razor-rules.md')
$artifactRules = Strip-Title (Read-Source 'artifact-rules.md')
$phases = (Get-Content (Join-Path $agents 'phases.json') -Raw | ConvertFrom-Json)
$skillDescription = 'Repository-aware, MCP-first feature engineering for Radzen Blazor. Use when adding or changing Radzen Blazor UI (grids, forms, dialogs, dashboards) or any feature that needs Radzen UI changes: detects the project, verifies Radzen APIs through the Radzen MCP, and enforces quality gates G0-G8.'

$skill = @"
---
name: speckit-radzen
description: $skillDescription
---

$generatedNote

# Spec Kit Radzen

$contractBody
"@

$blockBody = @"
## Spec Kit Radzen

For Radzen Blazor feature work, follow the Spec Kit Radzen operating contract: ``$kit/core/agents/operating-contract.md`` (skill ``speckit-radzen``).

- Run ``pwsh $kit/tools/speckit-radzen.ps1 status`` to see the current feature and the next step.
- Detect the project first (``detect``); follow the analogous feature; never add unapproved dependencies.
- Verify every Radzen API through the Radzen Blazor MCP and record it (``evidence add``); never invent Radzen members.
- Move through phases with ``phase``; pass gates with ``gate G0``…``G8``; quote gate results, never assume them.
- Hidden/disabled UI is not authorization. No secrets in tracked files (the MCP key comes from ``RADZEN_MCP_KEY``).
- Stop and ask on ambiguous authorization, unverifiable APIs, unapproved scope or dependency changes, or gate exit code 3.
"@

function New-PhaseText([object] $p, [string] $argumentLine) {
    $gateLine = if ($p.PSObject.Properties['gate'] -and $p.gate) { "Exit gate: **$($p.gate)**." } else { 'No exit gate; continue with the next phase.' }
    $roleLine = if ($p.PSObject.Properties['role'] -and $p.role) { "Act in the **$($p.role)** role (``$kit/core/agents/roles/$($p.role).md``)." } else { '' }
    $workflow = if ($p.PSObject.Properties['workflow']) { "Follow ``$kit/core/workflows/$($p.workflow)`` exactly, together with the constitution (``$kit/core/constitution/constitution.md``) and the operating contract (``$kit/core/agents/operating-contract.md``)." } else { '' }
    $util = switch ($p.id) {
        'status' { "Run ``pwsh $kit/tools/speckit-radzen.ps1 status`` and ``state``. Summarize the kit, profile health, MCP status and each feature's phase, gates and next step." }
        'gate' { "Run ``pwsh $kit/tools/speckit-radzen.ps1 gate <G#> -Feature <NNN> [-Slice S-##]`` for the gate named in the arguments. Quote the result, explain each failing check and propose fixes. Exit code 3 is a stop condition." }
        'scan' { "Run ``pwsh $kit/tools/speckit-radzen.ps1 scan -Feature <NNN>`` (or ``-All``). For each active finding explain the rule (``$kit/core/antipatterns/``) and propose the fix. Never add a waiver without a reason the user approved." }
        default { '' }
    }
@"
# Spec Kit Radzen — $($p.title)

$($p.summary)

$workflow
$util
$roleLine
$gateLine

Report using the operating contract's reporting format.

$argumentLine
"@
}

# ---------------- Claude Code ----------------
Save 'claude/dot-claude/skills/speckit-radzen/SKILL.md' $skill
foreach ($p in @($phases.phases) + @($phases.utilities)) {
    $text = New-PhaseText $p "User context: `$ARGUMENTS"
    Save "claude/dot-claude/commands/speckit-radzen.$($p.id).md" @"
---
description: Spec Kit Radzen — $($p.title): $($p.summary)
argument-hint: [feature number or request]
---

$generatedNote

$text
"@
}
foreach ($role in 'discoverer', 'reviewer') {
    $card = Strip-Title (Get-Content (Join-Path $agents 'roles' "$role.md") -Raw)
    $desc = if ($role -eq 'reviewer') { 'Independent Spec Kit Radzen reviewer. Use after all slices pass G5/G6 to review a Radzen feature against its spec, checklists and manual-review anti-patterns, and to run gate G7.' }
    else { 'Spec Kit Radzen discoverer. Use to trace how a requested Radzen feature fits the repository (read-only) and to write discovery.md for gate G1.' }
    $tools = if ($role -eq 'reviewer') { 'Read, Grep, Glob, Bash, Edit, Write' } else { 'Read, Grep, Glob, Bash, Write' }
    Save "claude/dot-claude/agents/speckit-radzen-$role.md" @"
---
name: speckit-radzen-$role
description: $desc
tools: $tools
---

$generatedNote

You are the Spec Kit Radzen **$role**. Kit folder: ``$kit``. Tool: ``pwsh $kit/tools/speckit-radzen.ps1``.

$card

Follow ``$kit/core/agents/operating-contract.md``. Report findings with IDs and evidence.
"@
}
Save 'claude/dot-claude/speckit-radzen.hooks.json' ([ordered]@{
        hooks = [ordered]@{
            PostToolUse = @([ordered]@{
                    matcher = 'Edit|Write|MultiEdit'
                    hooks   = @([ordered]@{ type = 'command'; command = "pwsh -NoProfile -File $kit/tools/speckit-radzen.ps1 scan"; timeout = 60 })
                })
        }
    } | ConvertTo-Json -Depth 10)
Save 'claude/CLAUDE.md.block' $blockBody

# ---------------- GitHub Copilot ----------------
Save 'copilot/dot-github/skills/speckit-radzen/SKILL.md' $skill
Save 'copilot/dot-github/copilot-instructions.md.block' $blockBody
Save 'copilot/dot-github/instructions/speckit-radzen-razor.instructions.md' @"
---
applyTo: "**/*.razor,**/*.razor.cs,**/*.razor.css"
description: Spec Kit Radzen rules for Razor files
---

$generatedNote

# Spec Kit Radzen — Razor rules

$razorRules
"@
Save 'copilot/dot-github/instructions/speckit-radzen-artifacts.instructions.md' @"
---
applyTo: "specs/**"
description: Spec Kit Radzen rules for feature artifacts
---

$generatedNote

# Spec Kit Radzen — artifact rules

$artifactRules
"@
foreach ($p in @($phases.phases) + @($phases.utilities)) {
    $text = New-PhaseText $p 'User context: ${input:request:Feature number or request}'
    Save "copilot/dot-github/prompts/speckit-radzen.$($p.id).prompt.md" @"
---
description: Spec Kit Radzen — $($p.title)
agent: agent
---

$generatedNote

$text
"@
}
$reviewerCard = Strip-Title (Get-Content (Join-Path $agents 'roles' 'reviewer.md') -Raw)
Save 'copilot/dot-github/agents/speckit-radzen-reviewer.agent.md' @"
---
description: Independent Spec Kit Radzen reviewer for Radzen Blazor features (gate G7).
---

$generatedNote

You are the Spec Kit Radzen **reviewer**. Kit folder: ``$kit``. Tool: ``pwsh $kit/tools/speckit-radzen.ps1``.

$reviewerCard
"@

# ---------------- Codex ----------------
Save 'codex/AGENTS.md.block' $blockBody
Save 'codex/dot-agents/skills/speckit-radzen/SKILL.md' $skill

# ---------------- Cursor ----------------
Save 'cursor/dot-cursor/rules/speckit-radzen.mdc' @"
---
description: Spec Kit Radzen operating contract for Radzen Blazor feature work
alwaysApply: true
---

$generatedNote

$contractBody
"@
Save 'cursor/dot-cursor/rules/speckit-radzen-razor.mdc' @"
---
description: Spec Kit Radzen rules for Razor files
globs: **/*.razor,**/*.razor.cs,**/*.razor.css
alwaysApply: false
---

$generatedNote

$razorRules
"@
Save 'cursor/dot-cursor/rules/speckit-radzen-artifacts.mdc' @"
---
description: Spec Kit Radzen rules for feature artifacts
globs: specs/**
alwaysApply: false
---

$generatedNote

$artifactRules
"@
foreach ($p in @($phases.phases) + @($phases.utilities)) {
    Save "cursor/dot-cursor/commands/speckit-radzen-$($p.id).md" @"
$generatedNote

$(New-PhaseText $p 'Use the text the user typed after the command as context.')
"@
}

# ---------------- Generic ----------------
Save 'generic/SPECKIT-RADZEN.md' @"
$generatedNote

$contract
"@
Save 'generic/dot-agents/skills/speckit-radzen/SKILL.md' $skill

$count = @(Get-ChildItem -Path $out -Recurse -File -Force).Count
Write-Host "Adapters generated: $count files -> $out"
