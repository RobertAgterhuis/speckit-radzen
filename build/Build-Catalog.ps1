#Requires -Version 7.4
<#
.SYNOPSIS
    Renders core/antipatterns/*.md from core/antipatterns/rules.json.
.PARAMETER OutputRoot
    Alternative output folder (used by Test-Drift.ps1).
#>
[CmdletBinding()]
param([string] $OutputRoot)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'core' 'antipatterns' 'rules.json'
$out = if ($OutputRoot) { $OutputRoot } else { Join-Path $root 'core' 'antipatterns' }
$null = New-Item -ItemType Directory -Force -Path $out
$rules = (Get-Content $source -Raw | ConvertFrom-Json).rules

$categories = [ordered]@{
    RDZ  = 'Radzen usage'
    RND  = 'Render mode and lifecycle'
    SEC  = 'Security'
    FRM  = 'Forms and validation'
    DAT  = 'Data access and volume'
    PERF = 'Performance'
    A11Y = 'Accessibility'
    RSP  = 'Responsive design'
    ARC  = 'Architecture'
    TST  = 'Testing'
    AGT  = 'Agent behaviour'
}
$detectionText = @{ regex = 'automated (scanner)'; absence = 'automated (scanner, absence check)'; tool = 'automated (tool)'; 'manual-review' = 'manual review (G7)' }
$utf8 = [System.Text.UTF8Encoding]::new($false)
function Save([string] $path, [string] $text) { [System.IO.File]::WriteAllText($path, ($text -replace "`r`n", "`n").TrimEnd() + "`n", $utf8) }
function Cell([string] $s) { ($s -replace '\|', '\|') }

$header = "<!-- Generated by build/Build-Catalog.ps1 from rules.json. Do not edit by hand. -->`n"
$index = [System.Text.StringBuilder]::new()
$null = $index.AppendLine($header)
$null = $index.AppendLine('# Anti-pattern Catalog')
$null = $index.AppendLine()
$null = $index.AppendLine("$($rules.Count) anti-patterns in $($categories.Count) categories. Source of truth: ``rules.json`` (schema ``core/schemas/antipattern-rules.schema.json``).")
$null = $index.AppendLine()
$null = $index.AppendLine('## How it is used')
$null = $index.AppendLine()
$null = $index.AppendLine('- **Automated** rules run in `speckit-radzen scan` and gate **G6** on changed files. `blocker` and `major` findings fail G6 unless waived.')
$null = $index.AppendLine('- **Manual review** rules are checked by the reviewer in phase 08 (**G7**); list them with `speckit-radzen scan -ListManual`.')
$null = $index.AppendLine('- **Waivers** need a reason: `@* speckit-radzen:ignore AP-XXX-00 reason="…" *@` (Razor) or `// speckit-radzen:ignore AP-XXX-00 reason="…"` (C#), on the same line or the line above. `speckit-radzen:ignore-file` waives a rule for the whole file. Repository-wide waivers go in `.speckit/radzen/config.json` → `scan.waivers`.')
$null = $index.AppendLine('- **Local rules:** `.speckit/radzen/local/antipatterns.local.json` (same format; same ID replaces a core rule).')
$null = $index.AppendLine()
$null = $index.AppendLine('## Summary')
$null = $index.AppendLine()
$null = $index.AppendLine('| ID | Title | Severity | Detection | Principles |')
$null = $index.AppendLine('|---|---|---|---|---|')
foreach ($cat in $categories.Keys) {
    foreach ($r in ($rules | Where-Object category -eq $cat)) {
        $null = $index.AppendLine("| [$($r.id)]($($r.doc)) | $(Cell $r.title) | $($r.severity) | $($detectionText[$r.detection]) | $($r.principles -join ', ') |")
    }
}
Save (Join-Path $out 'index.md') $index.ToString()

foreach ($cat in $categories.Keys) {
    $sb = [System.Text.StringBuilder]::new()
    $null = $sb.AppendLine($header)
    $null = $sb.AppendLine("# $($categories[$cat]) (AP-$cat)")
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('[Back to catalog](index.md)')
    foreach ($r in ($rules | Where-Object category -eq $cat)) {
        $null = $sb.AppendLine()
        $null = $sb.AppendLine("## $($r.id)")
        $null = $sb.AppendLine()
        $null = $sb.AppendLine("**$($r.title)** — severity **$($r.severity)**, $($detectionText[$r.detection]), principles $($r.principles -join ', ').")
        $null = $sb.AppendLine()
        $null = $sb.AppendLine("**Why it hurts.** $($r.why)")
        $null = $sb.AppendLine()
        $null = $sb.AppendLine("**Fix.** $($r.fix)")
        foreach ($pair in @(@('bad', 'Bad'), @('good', 'Good'))) {
            if ($r.PSObject.Properties[$pair[0]]) {
                $null = $sb.AppendLine()
                $null = $sb.AppendLine("**$($pair[1]):**")
                $null = $sb.AppendLine()
                $null = $sb.AppendLine('```razor')
                $null = $sb.AppendLine($r.($pair[0]))
                $null = $sb.AppendLine('```')
            }
        }
        if ($r.PSObject.Properties['mcpQuery']) {
            $null = $sb.AppendLine()
            $null = $sb.AppendLine("**Verify with MCP:** ``$($r.mcpQuery)``")
        }
        if ($r.detection -in 'regex', 'absence') {
            $tick = [char]96
            $parts = @("files $tick$($r.files -join "$tick, $tick")$tick", "pattern $tick$($r.pattern -replace $tick, "'")$tick")
            if ($r.PSObject.Properties['requires']) {
                $label = if ($r.detection -eq 'absence') { 'reported when the file lacks' } else { 'only when the file contains' }
                $parts += "$label $tick$($r.requires)$tick"
            }
            if ($r.PSObject.Properties['excludeTests'] -and $r.excludeTests) { $parts += 'test files excluded' }
            $null = $sb.AppendLine()
            $null = $sb.AppendLine("**Detection:** $($parts -join '; ').")
        }
        elseif ($r.detection -eq 'tool') {
            $null = $sb.AppendLine()
            $null = $sb.AppendLine("**Detection:** $($r.tool).")
        }
    }
    Save (Join-Path $out "$($cat.ToLowerInvariant()).md") $sb.ToString()
}
Write-Host "Catalog rendered: $($rules.Count) rules -> $out"
